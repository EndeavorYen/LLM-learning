CATEGORIES = {
    "NEG": "否定句：字面上提到 IN / OUT / BREAK / FIX，但明说没有发生，系统状态不变；正确类别 NOOP。",
    "OTHER": "别的系统：另一个同类系统（邻村的水塔、另一个停车场、另一只充电宝等）发生了 IN 或 OUT，与本系统无关；正确类别 NOOP。",
    "TEMP": "时间标记或倒叙（就在刚才 / 几分钟前 / 在这之前 / 早在……之前）：事件确实发生了；正确类别为事件本身。",
    "HEDGE": "不确定语气（好像 / 似乎 / 据说……但没人确认）：IN 或 BREAK 是否发生未经确认；不设正确类别，label 记为 UNCERTAIN，用来量信心是否下降。",
}


def label_of(cat, surface):
    return {"NEG": "NOOP", "OTHER": "NOOP", "TEMP": surface, "HEDGE": "UNCERTAIN"}[cat]


def main():
    raw = (BENCH / "templates.json").read_bytes()
    t = json.loads(raw)
    train = [d["name"] for d in t["domains"] if d["split"] == "train"]
    assert sorted(train) == sorted(DATA), (sorted(train), sorted(DATA))
    lines = ["{" + f'"version": "state_tracking_v1_hard", "templates_sha256": "{hashlib.sha256(raw).hexdigest()}",',
             ' "categories": ' + json.dumps(CATEGORIES, ensure_ascii=False) + ",",
             ' "domains": [']
    for di, name in enumerate(train):
        texts = DATA[name]
        assert len(texts) == len(SLOTS), (name, len(texts))
        lines.append(f'  {{"name": {json.dumps(name, ensure_ascii=False)}, "items": [')
        for k, ((cat, surf), txt) in enumerate(zip(SLOTS, texts)):
            item = {"id": f"{name}-{cat}-{surf}", "category": cat, "surface": surf,
                    "label": label_of(cat, surf), "text": txt}
            sep = "," if k < len(SLOTS) - 1 else ""
            lines.append("   " + json.dumps(item, ensure_ascii=False) + sep)
        lines.append("  ]}" + ("," if di < len(train) - 1 else ""))
    lines.append(" ]")
    lines.append("}")
    out = "\n".join(lines) + "\n"
    json.loads(out)  # sanity
    (BENCH / "hard_cases.json").write_text(out, encoding="utf-8")
    print("wrote", BENCH / "hard_cases.json", hashlib.sha256(out.encode("utf-8")).hexdigest())


if __name__ == "__main__":
    sys.exit(main())
