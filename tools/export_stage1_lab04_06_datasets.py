"""Regenerate benchmarks/stage1_lab04_06_datasets.json from the data the scripts actually use.

The previous JSON (committed in 684a82a) listed sentences that appear nowhere in the
Lab 04-06 scripts (see issue #17). This tool reads the literal data assignments straight
out of the scripts with `ast`, so the JSON can never drift from the code again.

Usage:  python tools/export_stage1_lab04_06_datasets.py
"""
import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCRIPTS = ROOT / "scripts"
OUT = ROOT / "benchmarks" / "stage1_lab04_06_datasets.json"


def literal(script: str, name: str):
    tree = ast.parse((SCRIPTS / script).read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", None) == name for t in node.targets):
            return ast.literal_eval(node.value)
    raise KeyError(f"{name} not found in {script}")


def main():
    lab04, lab05, lab06 = (
        "stage1_lab04_diffusion_vs_ar.py",
        "stage1_lab05_block_diffusion.py",
        "stage1_lab06_associative_thought.py",
    )
    data = {
        "_note": "Generated by tools/export_stage1_lab04_06_datasets.py from the scripts' literal data. Do not edit by hand.",
        "lab04_diffusion_vs_ar": {
            "script": f"scripts/{lab04}",
            "training_corpus": {
                "base_sentences": literal(lab04, "base_sentences"),
                "repeats_per_base_sentence": 40,
                "extra_web_texts": "first 300 lines of jingyaogong/minimind_dataset pretrain_t2t_mini.jsonl, "
                                   "kept if 30-80 chars, at most 120 (downloaded at run time)",
            },
            "cloze_test_cases": [
                {"prefix": p, "masked_answer": a, "suffix": s} for p, a, s in literal(lab04, "test_cases")
            ],
            "leakage_note": "every cloze test sentence is also a training sentence (issue #16)",
        },
        "lab05_block_diffusion": {
            "script": f"scripts/{lab05}",
            "training_sentences": [{"prompt": p, "continuation": c} for p, c in literal(lab05, "sentences")],
            "expand_task": {
                "left": "因为太阳光进入大气层时，",
                "masked_middle_target": "蓝光的波长比较短，容易被空气分子散射，",
                "right": "所以我们看到的天空是蓝色的。",
                "inserted_mask_slots": 16,
            },
            "modify_task": {"left": "周末下午我特地去了一趟", "masked_slots": 4,
                            "right": "，请专业医生帮我检查牙齿并清理了牙结石。"},
            "remove_and_heal_task": {"left": "周末下午我", "masked_slots": 4, "right": "面包准备做早餐。"},
            "leakage_note": "all expand / modify / remove inputs are training items (issue #16)",
        },
        "lab06_associative_thought": {
            "script": f"scripts/{lab06}",
            "thought_chains": [
                {"intent": name, "clauses": [{"detailed": d, "concise": c} for d, c in chain]}
                for name, chain in literal(lab06, "thought_chains")
            ],
            "leakage_note": "the seed and the ground-truth hop targets are training clauses (issue #16)",
        },
    }
    OUT.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
